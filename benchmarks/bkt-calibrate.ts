/**
 * Offline BKT calibration pipeline. Run with `npm run bench:bkt`.
 *
 * Reads graded responses (from the database when `DATABASE_URL` is set,
 * otherwise from the deterministic simulated world in `benchmarks/world.ts`),
 * fits the three compared variants, evaluates them, and writes:
 *
 *   benchmarks/bkt-calibration.json        full artifact + metrics
 *   benchmarks/BKT_CALIBRATION_RESULTS.md  human-readable report
 *
 * It NEVER writes to the database, the model registry, or any serving path.
 * Adopting parameters is a manual edit, by design — see BKT_CALIBRATION.md.
 *
 * Reproducibility: no `Math.random`, no wall-clock in the fit. The only
 * non-deterministic input is the dataset itself, which is fingerprinted into
 * the artifact as `datasetVersion`.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";

import {
  CURRENT_SERVING_PARAMS,
  DEFAULT_THRESHOLDS,
  assessEvidence,
  bktDatasetSignature,
  fitBktCalibration,
  splitBktResponses,
  type BktCalibrationArtifact,
  type BktResponseRow,
} from "../src/lib/ml/bkt-calibration";
import {
  compareBktVariants,
  evaluateVariant,
  type VariantEvaluation,
} from "../src/lib/ml/bkt-evaluation";
import { ARCHETYPES, BASE_WORLD, ITEMS, applyPractice, hashUniform, initialTrueState, trueProbCorrect } from "./world";

const OUT_DIR = join(process.cwd(), "benchmarks");
const PARAM_VERSION = process.env.BKT_PARAM_VERSION ?? "bkt-skill-candidate-1";

/* ------------------------------------------------------------------ */
/* Data sources                                                        */
/* ------------------------------------------------------------------ */

/**
 * Load real graded responses. Only `assessment_items` rows that were actually
 * answered count: an unanswered item carries no evidence and including it would
 * bias slip upward.
 */
async function loadFromDatabase(): Promise<BktResponseRow[]> {
  const { db } = await import("../src/db");
  const { assessmentItems, assessments } = await import("../src/db/schema");
  const { eq, isNotNull } = await import("drizzle-orm");

  const rows = await db
    .select({
      learnerId: assessments.studentId,
      skillId: assessmentItems.skillId,
      isCorrect: assessmentItems.isCorrect,
      occurredAt: assessmentItems.createdAt,
    })
    .from(assessmentItems)
    .innerJoin(assessments, eq(assessments.id, assessmentItems.assessmentId))
    .where(isNotNull(assessmentItems.isCorrect))
    .orderBy(assessmentItems.createdAt, assessmentItems.id);

  return rows.map((r) => ({
    learnerId: r.learnerId,
    skillId: r.skillId,
    isCorrect: Boolean(r.isCorrect),
    occurredAt: r.occurredAt as Date,
  }));
}

/**
 * Deterministic synthetic corpus from the existing simulation world, used when
 * no database is configured.
 *
 * This exists so the PIPELINE can be exercised and reviewed end-to-end, not so
 * parameters can be shipped from it: fitting BKT on data generated by a
 * different generative model and then serving the result would be circular. The
 * report marks any synthetic run as non-adoptable.
 */
function loadFromSimulation(learnerCount = 220, sessionsPerLearner = 14): BktResponseRow[] {
  const rows: BktResponseRow[] = [];
  const dayMs = 86_400_000;
  const epoch = Date.UTC(2026, 0, 1);

  for (let i = 0; i < learnerCount; i += 1) {
    const archetype = ARCHETYPES[i % ARCHETYPES.length];
    const truth = initialTrueState(archetype, BASE_WORLD);
    let day = 0;

    for (let session = 0; session < sessionsPerLearner; session += 1) {
      day += 1 + Math.floor(hashUniform(i, session, 7) * 3);
      const itemsThisSession = 4 + Math.floor(hashUniform(i, session, 11) * 5);

      for (let k = 0; k < itemsThisSession; k += 1) {
        const item = ITEMS[Math.floor(hashUniform(i, session, k, 3) * ITEMS.length)];
        const minutesThisSession = k * 1.5;
        const trueP = trueProbCorrect({ item, truth, day, archetype, world: BASE_WORLD, minutesThisSession });
        const isCorrect = hashUniform(i, session, k, 13) < trueP;
        const state = truth.skills.get(item.skillId);

        rows.push({
          learnerId: `sim-${i}`,
          skillId: `skill-${item.skillId}`,
          isCorrect,
          occurredAt: new Date(epoch + day * dayMs + k * 60_000),
          // Latent competence, recorded BEFORE the practice update so it is the
          // quantity a belief at decision time is trying to estimate.
          trueMastery: state ? state.ability : undefined,
        });

        applyPractice({ item, truth, day, isCorrect, trueP, archetype, world: BASE_WORLD, minutesThisSession });
      }
    }
  }
  return rows;
}

/* ------------------------------------------------------------------ */
/* Report rendering                                                    */
/* ------------------------------------------------------------------ */

function pct(x: number) {
  return `${(x * 100).toFixed(2)}%`;
}

function metricRow(label: string, v: VariantEvaluation) {
  const h = v.heldOutLearners;
  const c = v.chronological;
  return `| ${label} | ${c.brier.toFixed(5)} | ${pct(c.accuracy)} | ${c.calibrationError.toFixed(5)} | ${h.brier.toFixed(5)} | ${pct(h.accuracy)} | ${h.calibrationError.toFixed(5)} | ${h.masteryRmse ?? "n/a"} | ${v.temporal.brierStdDev.toFixed(5)} | ${pct(v.selection.zpdHitRate)} |`;
}

function renderReport(params: {
  source: "database" | "simulation";
  rows: number;
  learners: number;
  datasetVersion: string;
  evidence: ReturnType<typeof assessEvidence>;
  comparison: ReturnType<typeof compareBktVariants> | null;
  artifacts: Record<string, BktCalibrationArtifact>;
}) {
  const lines: string[] = [];
  lines.push("# BKT calibration results", "");
  lines.push(`_Generated by \`npm run bench:bkt\`. Source: **${params.source}**._`, "");

  if (params.source === "simulation") {
    lines.push(
      "> **NOT ADOPTABLE.** This run used the synthetic world in `benchmarks/world.ts`, whose",
      "> generative model is not BKT. It exercises the pipeline end-to-end; it cannot justify",
      "> shipping parameters. Re-run against production data before considering adoption.",
      "",
    );
  }

  lines.push("## Current serving parameterization (baseline)", "");
  lines.push("| Parameter | Value | Source |", "| --- | --- | --- |");
  lines.push(`| initial mastery (model prior) | ${CURRENT_SERVING_PARAMS.priorMastery} | \`models/bkt.ts\` DEFAULT_BKT_EXT |`);
  lines.push(`| learn | ${CURRENT_SERVING_PARAMS.learn} | \`knowledge-tracing.ts\` DEFAULT_BKT |`);
  lines.push(`| slip | ${CURRENT_SERVING_PARAMS.slip} | \`knowledge-tracing.ts\` DEFAULT_BKT |`);
  lines.push(`| guess | ${CURRENT_SERVING_PARAMS.guess} | \`knowledge-tracing.ts\` DEFAULT_BKT |`);
  lines.push(`| forget (per day) | ${CURRENT_SERVING_PARAMS.forget} | applied outside the recursion |`);
  lines.push("");

  lines.push("## Evidence", "");
  lines.push(`- responses: **${params.rows}** · learners: **${params.learners}** · skills: **${params.evidence.totalSkills}**`);
  lines.push(`- dataset signature: \`${params.datasetVersion}\``);
  lines.push(`- skills meeting per-skill thresholds: **${params.evidence.eligibleSkills.length}/${params.evidence.totalSkills}**`);
  lines.push("");
  lines.push("```");
  lines.push(params.evidence.requirement);
  lines.push("```");
  lines.push("");

  if (!params.comparison) {
    lines.push("## Outcome", "", "**Insufficient evidence — current implementation retained.** No parameters were fitted.", "");
    return lines.join("\n");
  }

  lines.push("## Variant comparison", "");
  lines.push(
    "| Variant | Brier (chrono) | Acc (chrono) | ECE (chrono) | Brier (held-out) | Acc (held-out) | ECE (held-out) | Mastery RMSE | Brier SD (temporal) | ZPD hit |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
  );
  for (const v of params.comparison.variants) lines.push(metricRow(v.variant, v));
  lines.push("");

  lines.push("## Promotion assessment", "");
  for (const [variant, report] of Object.entries(params.comparison.promotions)) {
    lines.push(`### ${variant}`, "");
    lines.push(`- recommendation: **${report.recommendation}**`);
    lines.push(`- verdict: ${report.decision.verdict}`);
    lines.push(`- auto-promote: ${report.autoPromote} (always false by design)`);
    for (const reason of report.rationale) lines.push(`  - ${reason}`);
    lines.push("");
  }

  lines.push("## Parameter coverage", "");
  for (const [variant, artifact] of Object.entries(params.artifacts)) {
    const entries = Object.values(artifact.skills);
    const fitted = entries.filter((e) => e.source === "fitted").length;
    const shrunk = entries.filter((e) => e.source === "shrunk").length;
    const fallback = entries.filter((e) => e.source === "global-fallback").length;
    const rejected = entries.filter((e) => e.flags.includes("rejected_degenerate")).length;
    lines.push(`- **${variant}** — fitted: ${fitted}, shrunk: ${shrunk}, global fallback: ${fallback}, rejected as degenerate: ${rejected}`);
  }
  lines.push("");
  lines.push("## Next gate", "");
  lines.push(
    "Offline metrics cannot measure what a re-parameterised policy would have *chosen*.",
    "Before adoption, run the candidate through the simulation harness (`npm run bench`) and",
    "then a shadow/experiment arm (`EXPERIMENTATION.md`). Editing the serving constants is a",
    "deliberate human step; nothing in this pipeline performs it.",
    "",
  );
  return lines.join("\n");
}

/* ------------------------------------------------------------------ */
/* Main                                                                */
/* ------------------------------------------------------------------ */

async function main() {
  const useDb = Boolean(process.env.DATABASE_URL) && process.env.BKT_SOURCE !== "simulation";
  let rows: BktResponseRow[] = [];
  let source: "database" | "simulation" = "simulation";

  if (useDb) {
    try {
      rows = await loadFromDatabase();
      source = "database";
    } catch (error) {
      console.error(`[bkt] database load failed (${(error as Error).name}); falling back to simulation.`);
      rows = [];
    }
  }
  if (!rows.length) {
    rows = loadFromSimulation();
    source = "simulation";
  }

  const datasetVersion = bktDatasetSignature(rows);
  const learners = new Set(rows.map((r) => String(r.learnerId))).size;
  const trainedThrough = new Date(
    Math.max(...rows.map((r) => (r.occurredAt instanceof Date ? r.occurredAt.getTime() : new Date(r.occurredAt).getTime()))),
  ).toISOString();

  // Gate 1: is there enough evidence at all? Checked on the FULL corpus before
  // splitting, so the answer does not depend on the split ratio.
  const evidence = assessEvidence(rows, DEFAULT_THRESHOLDS);
  console.log(`[bkt] source=${source} rows=${rows.length} learners=${learners} skills=${evidence.totalSkills}`);
  console.log(`[bkt] eligible skills: ${evidence.eligibleSkills.length}/${evidence.totalSkills}`);

  if (!evidence.sufficientForSkillSpecific) {
    console.log(`[bkt] INSUFFICIENT EVIDENCE — retaining current implementation.\n${evidence.requirement}`);
    const report = renderReport({ source, rows: rows.length, learners, datasetVersion, evidence, comparison: null, artifacts: {} });
    writeFileSync(join(OUT_DIR, "BKT_CALIBRATION_RESULTS.md"), `${report}\n`);
    writeFileSync(
      join(OUT_DIR, "bkt-calibration.json"),
      `${JSON.stringify({ source, datasetVersion, evidence, fitted: false, reason: "insufficient-evidence" }, null, 2)}\n`,
    );
    return;
  }

  const split = splitBktResponses(rows, { heldOutLearnerFraction: 0.2, trainRatio: 0.8 });
  console.log(
    `[bkt] split — train=${split.train.length} chrono-test=${split.chronologicalTest.length} ` +
      `held-out-learners=${split.heldOutLearnerTest.length} (${split.heldOutLearnerIds.length} learners)`,
  );

  const common = { datasetVersion, trainedThrough, thresholds: DEFAULT_THRESHOLDS };
  const artifacts: Record<string, BktCalibrationArtifact> = {
    "current-global": fitBktCalibration(split.train, { ...common, version: `${PARAM_VERSION}-global`, variant: "global" }),
    "skill-specific": fitBktCalibration(split.train, { ...common, version: `${PARAM_VERSION}-skill`, variant: "skill-specific" }),
    "skill-specific-shrunk": fitBktCalibration(split.train, { ...common, version: `${PARAM_VERSION}-shrunk`, variant: "skill-specific-shrunk" }),
  };

  const evaluations: Record<string, VariantEvaluation> = {};
  for (const [variant, artifact] of Object.entries(artifacts)) {
    evaluations[variant] = evaluateVariant({
      variant,
      artifact,
      chronologicalTest: split.chronologicalTest,
      heldOutLearnerTest: split.heldOutLearnerTest,
    });
  }

  const comparison = compareBktVariants({
    baseline: evaluations["current-global"],
    candidates: [evaluations["skill-specific"], evaluations["skill-specific-shrunk"]],
  });

  for (const v of comparison.variants) {
    console.log(
      `[bkt] ${v.variant.padEnd(22)} heldout-brier=${v.heldOutLearners.brier.toFixed(5)} ` +
        `acc=${(v.heldOutLearners.accuracy * 100).toFixed(2)}% ece=${v.heldOutLearners.calibrationError.toFixed(5)} ` +
        `own-params=${v.skillsWithOwnParams}`,
    );
  }
  console.log(`[bkt] best candidate: ${comparison.bestCandidate ?? "none — keep current parameters"}`);
  console.log("[bkt] promotion is NEVER automatic; edit the serving constants deliberately if adopting.");

  writeFileSync(
    join(OUT_DIR, "bkt-calibration.json"),
    `${JSON.stringify({ source, datasetVersion, trainedThrough, evidence, artifacts, comparison }, null, 2)}\n`,
  );
  writeFileSync(
    join(OUT_DIR, "BKT_CALIBRATION_RESULTS.md"),
    `${renderReport({ source, rows: rows.length, learners, datasetVersion, evidence, comparison, artifacts })}\n`,
  );
  console.log("[bkt] wrote benchmarks/bkt-calibration.json and benchmarks/BKT_CALIBRATION_RESULTS.md");
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
